/**
 * @fileoverview Unit test for scripts/build-leftovers.js: once a build is
 * done, the staged frontend (build/) and the schemas (gen/) and command
 * permissions (permissions/) Tauri's build script writes at the project
 * root are deleted, and Cargo's target/ is left alone.
 */

import assert from 'node:assert';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';
import { removeBuildLeftovers } from '../../../scripts/build-leftovers.js';

const root = join(dirname(fileURLToPath(import.meta.url)), `..`, `..`, `..`);

describe(`build-leftovers`, () => {
  it(`deletes build/, gen/ and permissions/ and keeps target/`, () => {
    for (const dir of [
      join(`build`, `frontend`),
      join(`gen`, `schemas`),
      join(`permissions`, `autogenerated`),
    ]) {
      mkdirSync(join(root, dir), { recursive: true });
      writeFileSync(join(root, dir, `leftover.txt`), `x`);
    }
    mkdirSync(join(root, `target`), { recursive: true });

    removeBuildLeftovers();

    for (const dir of [`build`, `gen`, `permissions`]) {
      assert.ok(!existsSync(join(root, dir)), `${dir}/ should be gone`);
    }
    assert.ok(existsSync(join(root, `target`)), `target/ should stay`);
  });
});
