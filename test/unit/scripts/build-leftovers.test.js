/**
 * @fileoverview Unit test for scripts/build-leftovers.js: once a build is
 * done, the staged frontend (build/) and the schemas (gen/) and command
 * permissions (permissions/) Tauri's build script writes at the project
 * root are deleted, and Cargo's target/ is left alone. The scripts run
 * from a copy in a project folder of its own, as the test files run beside
 * each other and stage-frontend.test.js uses the real build/.
 */

import assert from 'node:assert';
import { copyFileSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { after, before, describe, it } from 'node:test';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), `..`, `..`, `..`);
const project = join(root, `test-results`, `build-leftovers`);

describe(`build-leftovers`, () => {
  /** @type {() => void} */
  let removeBuildLeftovers;

  before(async () => {
    mkdirSync(join(project, `scripts`), { recursive: true });
    for (const script of [`build-leftovers.js`, `stage-frontend.js`]) {
      copyFileSync(join(root, `scripts`, script), join(project, `scripts`, script));
    }
    const copy = pathToFileURL(join(project, `scripts`, `build-leftovers.js`));
    ({ removeBuildLeftovers } = await import(copy.href));
  });

  after(() => {
    rmSync(project, { recursive: true, force: true });
  });

  it(`deletes build/, gen/ and permissions/ and keeps target/`, () => {
    for (const dir of [
      join(`build`, `frontend`),
      join(`gen`, `schemas`),
      join(`permissions`, `autogenerated`),
    ]) {
      mkdirSync(join(project, dir), { recursive: true });
      writeFileSync(join(project, dir, `leftover.txt`), `x`);
    }
    mkdirSync(join(project, `target`), { recursive: true });

    removeBuildLeftovers();

    for (const dir of [`build`, `gen`, `permissions`]) {
      assert.ok(!existsSync(join(project, dir)), `${dir}/ should be gone`);
    }
    assert.ok(existsSync(join(project, `target`)), `target/ should stay`);
  });
});
